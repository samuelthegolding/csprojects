import java.util.*;

public class Tree<E extends Comparable<? super E>> {
    private BinaryTreeNode root;  // Root of tree
    private String name;     // Name of tree

    /**
     * Create an empty tree
     *
     * @param label Name of tree
     */
    public Tree(String label) {
        name = label;
    }

    /**
     * Create BST from ArrayList
     *
     * @param arr   List of elements to be added
     * @param label Name of tree
     */
    public Tree(ArrayList<E> arr, String label) {
        name = label;
        for (E key : arr) {
            insert(key);
        }
    }

    /**
     * Create BST from Array
     *
     * @param arr   List of elements to be added
     * @param label Name of  tree
     */
    public Tree(E[] arr, String label) {
        name = label;
        for (E key : arr) {
            insert(key);
        }
    }

    /**
     * Return a string containing the tree contents as a tree with one node per line
     */
    public String toString() {
        if (root == null) return name + " is empty";
        StringBuilder sb = new StringBuilder();
        sb.append(name).append(": \n");
        bstStringGen(root, sb, 0, "no parent");

        return sb.toString();
    }

    /**
     * Recursive Function to generate string
     *
     * @param node   Referred node that is treated as the root of the subtree
     * @param sb     The String Builder generated by the toString function
     * @param level  A level parameter to allow for correct spacing
     * @param parent The parent node to add to the 'sideways' view
     */
    private void bstStringGen(BinaryTreeNode node, StringBuilder sb, int level, String parent) {
        if (node == null) return;
        bstStringGen(node.right, sb, ++level, node.key.toString());

        sb.append(" ".repeat(level)).append(node.key).append(" [").append(parent).append("]\n");
        bstStringGen(node.left, sb, ++level, node.key.toString());
    }

    /**
     * Return a string containing the tree contents as a single line
     */
    public String inOrderToString() {
        return name + ": " + inOrderStringGen(root);
    }

    /**
     * Performs an In-Order traversal
     *
     * @param node the node that is being treated as the root of the subtree
     * @return an InOrder traversal of each subtree
     */
    private String inOrderStringGen(BinaryTreeNode node) {
        if (node == null) return "";
        String inOrderLeft = inOrderStringGen(node.left);
        String value = node.key + " ";
        String inOrderRight = inOrderStringGen(node.right);
        return inOrderLeft + value + inOrderRight;
    }

    /**
     * reverse left and right children recursively
     */
    public void flip() {
        recurFlipper(root);
    }

    /**
     * Recursive Flipper of the tree
     *
     * @param node root of subtree
     */
    private void recurFlipper(BinaryTreeNode node) {
        if (node == null) return;
        BinaryTreeNode left = node.left;
        BinaryTreeNode right = node.right;
        node.left = right;
        node.right = left;
        recurFlipper(left);
        recurFlipper(right);

    }

    /**
     * Returns the in-order successor of the specified node
     *
     * @param node node from which to find the in-order successor
     */
    public BinaryTreeNode inOrderSuccessor(BinaryTreeNode node) {
        if (node == null) return null;
        if (node.right == null) {
            BinaryTreeNode parent = node.parent;
            if (parent == null) return null;
            if (parent.right == null) {
                return parent;
            }
            if (parent.right != node) {
                return node.parent;
            }
            return (goUp(parent));
        } else {
            return goLeft(node.right);
        }

    }

    /**
     * Go down and to the left
     * @param node node that being acted on
     * @return far left node
     */
    private BinaryTreeNode goLeft(BinaryTreeNode node) {
        if (node == null) return null;
        if (node.left != null) {
            return goLeft(node.left);
        }
        return node;
    }

    /**
     * Go up, as long as node is the right child
     * @param node Node that is being looked at
     * @return the first left child
     */
    private BinaryTreeNode goUp(BinaryTreeNode node) {
        BinaryTreeNode parent = node.parent;
        if (parent == null) return null;
        if (parent.right == node) {
            return goUp(parent);
        } else {
            return parent;
        }
    }

    /**
     * Counts number of nodes in specified level
     *
     * @param level Level in tree, root is zero
     * @return count of number of nodes at specified level
     */
    public int nodesInLevel(int level) {
        return (recurNodes(root, level));
    }

    /**
     * Recursive method that takes in the root node and a desired level, and recursively enters the tree until it has
     * entered a 'level' amount of times, and returns one for each of those points.
     *
     * @param node  BinaryTreeNode to act as the root of a subtree
     * @param level desired level on which to print the amount of nodes
     * @return an integer representing the number of nodes in a level
     */
    private int recurNodes(BinaryTreeNode node, int level) {
        if (node == null) return 0;
        if (level == 0) return 1;
        return (recurNodes(node.left, level - 1) + recurNodes(node.right, level - 1));
    }

    /**
     * Print all paths from root to leaves
     */
    public void printAllPaths() {
        ArrayList<E> leavesList = new ArrayList<>();
        if (root == null) {
            System.out.println("Tree is empty");
            return;
        }
        findAllLeaves(root, leavesList);
        for (E key : leavesList) {
            StringBuilder path = new StringBuilder();

            System.out.println(printPath(key, root, path));
        }

    }

    /**
     * Recursive method that finds leaf nodes and adds them to leavesList
     *
     * @param node       node treated as  root of subtree
     * @param leavesList ArrayList passed into be able to be added
     */
    private void findAllLeaves(BinaryTreeNode node, ArrayList<E> leavesList) {
        if (node.left == null && node.right == null) {
            // Avoids duplicates
            if (!leavesList.contains(node.key)) {
                leavesList.add(node.key);
            }

            // Breakout Condition.
            return;
        }

        // Recurses both left and right
        if (node.left != null) {
            findAllLeaves(node.left, leavesList);
        }
        if (node.right != null) {
            findAllLeaves(node.right, leavesList);
        }
    }

    /**
     * Function that finds the path to the parameter key
     *
     * @param key  Comparable value that is used to compare nodes against
     * @param node Node being compared against
     * @param path StringBuilder that is returned and printed after
     */
    private StringBuilder printPath(E key, BinaryTreeNode node, StringBuilder path) {
        if (key == null || node == null) return path.append("Path is Empty");
        path.append(node.key).append(" ");
        if (key.compareTo(node.key) == 0) {
            return path;
        }
        if (key.compareTo(node.key) < 0) {
            printPath(key, node.left, path);
        }
        if (key.compareTo(node.key) > 0) {
            printPath(key, node.right, path);
        }
        return path;
    }

    /**
     * Counts all non-null binary search trees embedded in tree
     *
     * @return Count of embedded binary search trees
     */
    public int countBST() {
        // Call recursive method to count subtrees
        return recurCountBST(root);
    }

    /**
     * Recursively counts subtrees
     *
     * @param node head of subtree
     * @return integer count of subtrees that are also BSTs
     */
    private int recurCountBST(BinaryTreeNode node) {
        // Return zero if outside of tree
        if (node == null) return 0;

        // Recursively count to both left and right
        int count = recurCountBST(node.left) + recurCountBST(node.right);

        // If binary tree add to count value and return count value
        if (isBTaBST(node, null, null)) {
            count++;
        }
        return count;
    }

    /**
     * Recursive function that returns whether the Binary Tree is a Binary Search Tree
     *
     * @param subRoot Node treated as the subRoot of a tree/ root of a subtree
     * @param min     minimum value
     * @param max     maximum value
     * @return boolean representing whether the node is the head of a subtree
     */
    private boolean isBTaBST(BinaryTreeNode subRoot, E min, E max) {
        // If referenced node is null or has no data,  it has passed all tests without returning false,
        // and therefore the nodes above it constitute a BST
        if (subRoot == null || subRoot.key == null) return true;

        // If the minimum is > the key, then the subtree is not a BST
        if (min != null && min.compareTo(subRoot.key) >= 0) {
            return false;
        }
        // If the maximum is < the key, then the subtree is not a BST
        if (max != null && max.compareTo(subRoot.key) <= 0) {
            return false;
        }

        // Recurse to continue search
        return (isBTaBST(subRoot.left, min, subRoot.key)) && (isBTaBST(subRoot.right, subRoot.key, max));
    }

    /**
     * Insert into a bst tree; duplicates are allowed
     *
     * @param x the item to insert.
     */
    public void insert(E x) {
        root = insert(x, root, null);
    }

    /**
     * Method that returns a Node where a key is located.
     *
     * @param key key to be searched for
     * @return BinaryTreeNode that is being searched for
     */
    public BinaryTreeNode getByKey(E key) {
        return keyFinder(key, root);
    }

    /**
     * Recursive method that finds the key within the BST
     *
     * @param key  key to be searched for
     * @param node BinaryTreeNode treated as root of subtree
     * @return BinaryTreeNode such that node.key = key
     */
    private BinaryTreeNode keyFinder(E key, BinaryTreeNode node) {
        if (node == null) return null;
        if (key.compareTo(node.key) < 0) {
            return keyFinder(key, node.left);
        } else if (key.compareTo(node.key) > 0) {
            return keyFinder(key, node.right);
        } else {
            return node;
        }
    }

    /**
     * Balance the tree
     */
    public void balanceTree() {
        // TODO:
        ArrayList<E> list = new ArrayList<>();
        inOrderTraverse(root, list);
        root = balancer(list, 0, list.size() - 1);
    }

    /**
     * Internal Method that takes a list created by an inOrder Traversal and does
     * a recursive binary insert
     *
     * @param list  inOrder list of items in original tree
     * @param start index that the insertion starts at
     * @param end   index that the insertion ends at
     * @return new tree
     */
    private BinaryTreeNode balancer(ArrayList<E> list, int start, int end) {
        if (start > end) return null;
        int mid = (start + end) / 2;
        BinaryTreeNode root = insert(list.get(mid), null, null);
        root.left = balancer(list, start, mid - 1);
        root.right = balancer(list, mid + 1, end);
        return root;
    }

    /**
     * Recursive method that returns an inOrder list of the BST
     *
     * @param node node treated as root of subtree
     * @param list list to add nodes in order.
     */
    private void inOrderTraverse(BinaryTreeNode node, ArrayList<E> list) {
        if (node == null) return;
        inOrderTraverse(node.left, list);
        list.add(node.key);
        inOrderTraverse(node.right, list);
    }

    /**
     * Internal method to insert into a subtree.
     * In tree is balanced, this routine runs in O(log n)
     *
     * @param x the item to insert.
     * @param t the node that roots the subtree.
     * @return the new root of the subtree.
     */
    private BinaryTreeNode insert(E x, BinaryTreeNode t, BinaryTreeNode parent) {
        if (t == null) return new BinaryTreeNode(x, null, null, parent);

        int compareResult = x.compareTo(t.key);
        if (compareResult < 0) {
            t.left = insert(x, t.left, t);
        } else {
            t.right = insert(x, t.right, t);
        }

        return t;
    }


    /**
     * Internal method to find an item in a subtree.
     * This routine runs in O(log n) as there is only one recursive call that is executed and the work
     * associated with a single call is independent of the size of the tree: a=1, b=2, k=0
     *
     * @param x is item to search for.
     * @param t the node that roots the subtree.
     *          SIDE EFFECT: Sets local variable curr to be the node that is found
     * @return node containing the matched item.
     */
    private boolean contains(E x, BinaryTreeNode t) {
        if (t == null)
            return false;

        int compareResult = x.compareTo(t.key);

        if (compareResult < 0)
            return contains(x, t.left);
        else if (compareResult > 0)
            return contains(x, t.right);
        else {
            return true;    // Match
        }
    }

    // Basic node stored in unbalanced binary trees
    public class BinaryTreeNode {
        E key;            // The data/key for the node
        BinaryTreeNode left;   // Left child
        BinaryTreeNode right;  // Right child
        BinaryTreeNode parent; //  Parent node

        // Constructors
        BinaryTreeNode(E theElement) {
            this(theElement, null, null, null);
        }

        BinaryTreeNode(E theElement, BinaryTreeNode lt, BinaryTreeNode rt, BinaryTreeNode pt) {
            key = theElement;
            left = lt;
            right = rt;
            parent = pt;
        }

        @Override
        public String toString() {
            StringBuilder sb = new StringBuilder();
            sb.append("Node:");
            sb.append(key);
            if (parent == null) {
                sb.append("<>");
            } else {
                sb.append("<");
                sb.append(parent.key);
                sb.append(">");
            }

            return sb.toString();
        }
    }
}
